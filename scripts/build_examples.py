"""Regenerate js/examples.js from the AdaptPolicies few-shot examples.

Usage: python scripts/build_examples.py <path to AdaptPolicies repo>

Videos: put an MP4 in videos/ named after the task (e.g. videos/wash_clothes.mp4);
this script links every video it finds to its task.
"""
import json, sys
from pathlib import Path

repo = Path(sys.argv[1] if len(sys.argv) > 1 else "../AdaptPolicies")
ex = repo / "src/methods/adaptive/examples"
site = Path(__file__).resolve().parent.parent
videos = {p.stem for p in (site / "videos").glob("*.mp4")}


def title(task):
    return task.replace("_", " ").capitalize()


policies = [{"task": t, "title": title(t), "code": code,
             "video": f"videos/{t}.mp4" if t in videos else None}
            for t, code in json.load(open(ex / "policy.json")).items()]
recoveries = []
for kind, name in (("recover.json", "Local recovery"), ("regenerate_helper.json", "Helper regeneration"),
                   ("replan.json", "Re-planning")):
    for e in json.load(open(ex / kind)):
        recoveries.append({"level": name, "task": e["task"], "title": f"{name}: {title(e['task'])}",
                           "trigger": e["trigger"], "failure": e["failure"],
                           "observation": e.get("observation"), "code": e["code"]})

out = site / "js" / "examples.js"
out.write_text("// Generated by scripts/build_examples.py; do not edit by hand.\n"
               f"window.AP_POLICIES = {json.dumps(policies, indent=1)};\n"
               f"window.AP_RECOVERIES = {json.dumps(recoveries, indent=1)};\n", encoding="utf-8")
print(f"{len(policies)} policies ({len(videos & {p['task'] for p in policies})} with video), "
      f"{len(recoveries)} recovery examples -> {out}")
